_SITE_BY_SLUG = {site["slug"]: site for site in SITES}


def _report(
    report_id: str,
    site_slug: str,
    title: str,
    published: str,
    category: str,
    summary: str,
    observation: str,
    *,
    campaign: str | None = None,
    actors: tuple[str, ...] = (),
    malware: tuple[str, ...] = (),
    tools: tuple[str, ...] = (),
    vulnerabilities: tuple[str, ...] = (),
    indicators: tuple[str, ...] = (),
    techniques: tuple[str, ...] = (),
    sectors: tuple[str, ...] = (),
    region: str = "Fictional multi-region",
    related: tuple[str, ...] = (),
    annotation: str = "campaign_evidence",
    duplicate_scenario: str | None = None,
    body_override: str | None = None,
) -> dict[str, Any]:
    site = _SITE_BY_SLUG[site_slug]
    entity_lines = []
    for label, values in (
        ("Threat actor", actors),
        ("Malware family", malware),
        ("Tool", tools),
        ("Vulnerability", vulnerabilities),
        ("Indicator", indicators),
        ("ATT&CK reference", techniques),
        ("Target sector", sectors),
    ):
        if values:
            entity_lines.append(f"{label}: {', '.join(values)}.")
    body = body_override or " ".join(
        [
            "SIMULATED DEMONSTRATION INTELLIGENCE — every organisation, operator, family, and indicator in this article is fictional.",
            f"{site['name']} documents {observation}",
            *entity_lines,
            f"The assessment is limited to the evidence quoted here; shared infrastructure, tools, or techniques alone do not prove common control. The named region is {region}.",
            "All network indicators use documentation-only address space or the reserved .example namespace; hashes are synthetic fixtures and must not be used as live threat data.",
        ]
    )
    return {
        "id": report_id,
        "title": title,
        "source_name": site["name"],
        "source_slug": site_slug,
        "published": f"{published}T12:00:00Z",
        "category": category,
        "summary": summary,
        "content": body,
        "campaign_name": campaign,
        "threat_actor": list(actors),
        "malware_family": list(malware),
        "tools": list(tools),
        "vulnerabilities": list(vulnerabilities),
        "indicators": list(indicators),
        "attack_techniques": list(techniques),
        "target_sectors": list(sectors),
        "region": region,
        "related_report_ids": list(related),
        "demo_annotation": annotation,
        "duplicate_scenario": duplicate_scenario,
        "url": f"/demo-sites/{site_slug}/reports/{quote(report_id, safe='')}",
        "fictional_demo": True,
    }


