def reports_for_site(site_slug: str) -> list[dict[str, Any]]:
    return [report for report in REPORTS if report["source_slug"] == site_slug]


def report_by_id(report_id: str) -> dict[str, Any] | None:
    return next((report for report in REPORTS if report["id"] == report_id), None)


def site_by_slug(site_slug: str) -> dict[str, str] | None:
    return _SITE_BY_SLUG.get(site_slug)


def feed_payload(site_slug: str) -> dict[str, Any]:
    site = site_by_slug(site_slug)
    if site is None:
        raise KeyError(site_slug)
    items = []
    for report in reports_for_site(site_slug):
        items.append({
            "id": report["id"],
            "title": report["title"],
            "summary": report["summary"],
            "content": report["content"],
            "published": report["published"],
            "url": f"http://127.0.0.1:8000{report['url']}",
            "category": report["category"],
            "campaign_name": report["campaign_name"],
            "threat_actor": report["threat_actor"],
            "malware_family": report["malware_family"],
            "tools": report["tools"],
            "vulnerabilities": report["vulnerabilities"],
            "indicators": report["indicators"],
            "attack_techniques": report["attack_techniques"],
            "target_sectors": report["target_sectors"],
            "region": report["region"],
            "related_report_ids": report["related_report_ids"],
            "demo_annotation": report["demo_annotation"],
            "duplicate_scenario": report["duplicate_scenario"],
            "fictional_demo": True,
        })
    return {
        "feed_title": site["name"],
        "feed_url": f"http://127.0.0.1:8000/demo-sites/{site_slug}/feed.json",
        "updated": datetime.now(timezone.utc).isoformat(),
        "fictional_demo": True,
        "items": items,
    }


def demo_report_counts() -> dict[str, int]:
    counts = {"total": len(REPORTS), "campaign_evidence": 0, "partial_evidence": 0, "hard_negative": 0, "unrelated": 0}
    for report in REPORTS:
        key = str(report["demo_annotation"])
        if key in counts:
            counts[key] += 1
    return counts
